import { createLeadSchema, toFieldErrors, updateLeadSchema } from "@/lib/validation";
import type { LeadInsert, LeadUpdate } from "@/lib/database.types";
import { logActivity, type ActorOptions } from "./activities";
import { recalculateScore } from "./pipeline";
import { dbError, type DB, type Lead, type ServiceResult } from "./types";

/** Fields compared for the "updated" timeline entry (status has its own event). */
const TRACKED_FIELDS = [
  "brand_name", "owner_name", "phone", "whatsapp", "email", "instagram", "website",
  "city", "state", "country", "niche", "logo_url", "source", "notes",
] as const;

type DuplicateKeys = Pick<LeadInsert, "phone" | "whatsapp" | "instagram" | "website" | "brand_name" | "city">;

/**
 * Finds existing leads that share a phone / WhatsApp / Instagram / website,
 * or the same brand name + city. Input must already be normalised.
 */
export async function findDuplicateLeads(
  db: DB,
  keys: Partial<DuplicateKeys>,
  excludeId?: string,
): Promise<ServiceResult<Lead[]>> {
  const { data, error } = await db.rpc("find_duplicate_leads", {
    p_phone: keys.phone ?? null,
    p_whatsapp: keys.whatsapp ?? null,
    p_instagram: keys.instagram ?? null,
    p_website: keys.website ?? null,
    p_brand_name: keys.brand_name ?? null,
    p_city: keys.city ?? null,
    p_exclude_id: excludeId ?? null,
  });
  if (error) return dbError(error);
  return { ok: true, data: data ?? [] };
}

/**
 * Validates, checks for duplicates and inserts a new lead.
 * The tracking ID is generated by the database. If a matching lead already
 * exists, nothing is inserted and `{ code: "duplicate", duplicates }` is returned.
 */
export type AddLeadOptions = ActorOptions & {
  /** Links the lead to a PDF import (imports.id). */
  importId?: string | null;
};

export async function addLead(db: DB, input: unknown, options: AddLeadOptions = {}): Promise<ServiceResult<Lead>> {
  const parsed = createLeadSchema.safeParse(input);
  if (!parsed.success) {
    return {
      ok: false,
      code: "validation",
      message: "Please fix the highlighted fields.",
      fieldErrors: toFieldErrors(parsed.error),
    };
  }
  const lead = parsed.data;

  const dup = await findDuplicateLeads(db, lead);
  if (!dup.ok) return dup;
  if (dup.data.length > 0) {
    return {
      ok: false,
      code: "duplicate",
      message: "This lead already exists. No new ID was created.",
      duplicates: dup.data,
    };
  }

  const row: LeadInsert = options.importId ? { ...lead, import_id: options.importId } : lead;
  const { data, error } = await db.from("leads").insert(row).select("*").single();
  if (error) return dbError(error);
  await logActivity(db, data.id, "created", { source: data.source, tracking_id: data.tracking_id }, options.actor);
  const scored = await recalculateScore(db, data.id);
  return { ok: true, data: scored.ok ? scored.data : data };
}

export type UpdateOptions = ActorOptions & {
  /** Skip the duplicate check (e.g. when merging new details into an existing lead). */
  allowDuplicates?: boolean;
  /** Only apply non-empty values; never clear existing fields. */
  onlyFilled?: boolean;
};

/** Updates a lead by id. The tracking ID can never change. */
export async function updateLead(
  db: DB,
  id: string,
  input: unknown,
  options: UpdateOptions = {},
): Promise<ServiceResult<Lead>> {
  const parsed = updateLeadSchema.safeParse(input);
  if (!parsed.success) {
    return {
      ok: false,
      code: "validation",
      message: "Please fix the highlighted fields.",
      fieldErrors: toFieldErrors(parsed.error),
    };
  }

  let patch: LeadUpdate = parsed.data;
  // undefined keys are "not provided"; drop them so they are not sent.
  patch = Object.fromEntries(
    Object.entries(patch).filter(([, v]) => v !== undefined && (!options.onlyFilled || v !== null)),
  ) as LeadUpdate;
  const current = await getLeadById(db, id);
  if (!current.ok) return current;
  if (Object.keys(patch).length === 0) return current;

  if (!options.allowDuplicates) {
    const merged = { ...current.data, ...patch };
    const dup = await findDuplicateLeads(db, merged, id);
    if (!dup.ok) return dup;
    if (dup.data.length > 0) {
      return {
        ok: false,
        code: "duplicate",
        message: "Another lead already uses some of these details.",
        duplicates: dup.data,
      };
    }
  }

  const statusChanged = patch.status !== undefined && patch.status !== current.data.status;
  if (statusChanged && patch.status && ["Contacted", "Interested", "Deal Closed"].includes(patch.status)) {
    patch.last_contacted_at = new Date().toISOString();
  }

  const { data, error } = await db.from("leads").update(patch).eq("id", id).select("*").maybeSingle();
  if (error) return dbError(error);
  if (!data) return { ok: false, code: "not_found", message: "Lead not found." };

  const changes: Record<string, { old: unknown; new: unknown }> = {};
  for (const f of TRACKED_FIELDS) {
    if (f in patch && (current.data[f] ?? null) !== (data[f] ?? null)) changes[f] = { old: current.data[f], new: data[f] };
  }
  if (Object.keys(changes).length) await logActivity(db, id, "updated", { changes }, options.actor);
  if (statusChanged) {
    await logActivity(db, id, "status_changed", { old: current.data.status, new: data.status }, options.actor);
  }
  const scored = await recalculateScore(db, id);
  return { ok: true, data: scored.ok ? scored.data : data };
}

/** Smart search across tracking ID, brand, owner, phone, WhatsApp, Instagram, website, email. */
export async function searchLeads(
  db: DB,
  query: string,
  options: { limit?: number } = {},
): Promise<ServiceResult<Lead[]>> {
  const { data, error } = await db.rpc("search_leads", {
    p_query: query.slice(0, 200),
    p_limit: options.limit ?? 50,
  });
  if (error) return dbError(error);
  return { ok: true, data: data ?? [] };
}

export async function getLeadByTrackingId(db: DB, trackingId: string): Promise<ServiceResult<Lead>> {
  const { data, error } = await db
    .from("leads")
    .select("*")
    .eq("tracking_id", trackingId.trim().toUpperCase())
    .maybeSingle();
  if (error) return dbError(error);
  if (!data) return { ok: false, code: "not_found", message: `No lead with ID ${trackingId}.` };
  return { ok: true, data };
}

export async function getLeadById(db: DB, id: string): Promise<ServiceResult<Lead>> {
  const { data, error } = await db.from("leads").select("*").eq("id", id).maybeSingle();
  if (error) return dbError(error);
  if (!data) return { ok: false, code: "not_found", message: "Lead not found." };
  return { ok: true, data };
}

const MERGE_FIELDS = [
  "owner_name",
  "phone",
  "whatsapp",
  "email",
  "instagram",
  "website",
  "city",
  "niche",
  "logo_url",
] as const satisfies readonly (keyof LeadInsert)[];

/**
 * Merges new details into an existing lead without losing anything:
 * empty fields on the existing lead are filled in; values that differ from
 * what is already stored are kept in the notes instead of overwriting.
 * The tracking ID, brand name, state and status never change.
 */
export async function mergeLeadDetails(
  db: DB,
  existing: Lead,
  incoming: LeadInsert,
  sourceLabel: string,
  options: ActorOptions & { importId?: string } = {},
): Promise<ServiceResult<Lead>> {
  const patch: LeadUpdate = {};
  const conflicts: string[] = [];
  for (const field of MERGE_FIELDS) {
    const next = incoming[field];
    if (!next) continue;
    const current = existing[field];
    if (!current) patch[field] = next;
    else if (String(current).toLowerCase() !== String(next).toLowerCase()) conflicts.push(`${field.replace("_", " ")}: ${next}`);
  }
  if (incoming.state && incoming.state !== existing.state) conflicts.push(`state: ${incoming.state}`);
  const extraNotes = [incoming.notes, conflicts.length ? `Other details — ${conflicts.join("; ")}` : null]
    .filter(Boolean)
    .join(" · ");
  if (extraNotes && !(existing.notes ?? "").includes(extraNotes)) {
    patch.notes = [existing.notes, `[${sourceLabel}] ${extraNotes}`].filter(Boolean).join("\n");
  }
  const filled = Object.keys(patch).filter((k) => k !== "notes");
  const details = {
    from: sourceLabel,
    ...(options.importId ? { import_id: options.importId } : {}),
    filled,
    conflicts,
  };
  if (Object.keys(patch).length === 0) {
    await logActivity(db, existing.id, "merged", details, options.actor);
    return { ok: true, data: existing };
  }

  const { data, error } = await db.from("leads").update(patch).eq("id", existing.id).select("*").maybeSingle();
  if (error) return dbError(error);
  if (!data) return { ok: false, code: "not_found", message: "Lead not found." };
  await logActivity(db, existing.id, "merged", details, options.actor);
  const scored = await recalculateScore(db, existing.id);
  return { ok: true, data: scored.ok ? scored.data : data };
}
